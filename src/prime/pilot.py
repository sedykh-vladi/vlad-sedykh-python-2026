"""Расчёты для пилотов (A/B-тестов): семинары С7 и С8.

Здесь пять функций, которыми считает ноутбук ДЗ-3.

С7, планирование эксперимента:
    n_per_group  — сколько клиентов нужно в каждую группу;
    mde_for_n    — обратная задача: какой минимальный эффект заметит эксперимент.

С8, анализ итогов:
    diff_ci      — разность средних test − control, её интервал и p-значение;
    srm_pvalue   — проверка, что группы получились нужного размера (SRM);
    cuped        — поправка CUPED, которая уменьшает разброс метрики.

Импорты только из стандартной библиотеки. Так модуль работает и в основном
окружении prime-monitor (там нет scipy), и в окружении pilot/ с HypEx.
"""

import math
from statistics import NormalDist

# Квантиль стандартного нормального распределения: z(0.975) ≈ 1.96.
z = NormalDist().inv_cdf


# ---------------------------------------------------------------------------
# С7. Планирование: объём выборки и минимальный заметный эффект
# ---------------------------------------------------------------------------

def n_per_group(sigma: float, mde: float, alpha: float = 0.05, power: float = 0.8,
                comparisons: int = 1) -> int:
    """Сколько клиентов нужно в КАЖДУЮ группу, чтобы заметить эффект mde.

    sigma        — стандартное отклонение метрики (например, оборота), ₽;
    mde          — минимальный эффект, который хотим заметить, ₽;
    alpha        — допустимая доля ложных срабатываний;
    power        — мощность, то есть шанс заметить эффект, если он есть;
    comparisons  — сколько тестовых групп сравниваем с контролем
                   (поправка Бонферрони: alpha делится между сравнениями).
    """
    za = z(1 - alpha / (2 * comparisons))   # порог значимости, двусторонний
    zb = z(power)                           # запас на мощность
    return math.ceil(2 * (za + zb) ** 2 * sigma ** 2 / mde ** 2)


def mde_for_n(sigma: float, n: int, alpha: float = 0.05, power: float = 0.8,
              comparisons: int = 1) -> float:
    """Какой минимальный эффект заметит эксперимент с n клиентами в каждой группе.

    Это та же формула, что в n_per_group, только решённая относительно mde:
        mde = (z_{1-alpha/(2k)} + z_{power}) * sigma * sqrt(2 / n).
    """
    za = z(1 - alpha / (2 * comparisons))
    zb = z(power)
    return (za + zb) * sigma * math.sqrt(2 / n)


# ---------------------------------------------------------------------------
# С8. Анализ: эффект с интервалом, SRM и CUPED
# ---------------------------------------------------------------------------

def diff_ci(t, c, alpha: float = 0.05) -> dict:
    """Разность средних test − control, её доверительный интервал и p-значение.

    t, c — значения метрики в тестовой и контрольной группе (pandas.Series).
    Стандартная ошибка считается по дисперсии каждой группы отдельно (как у Уэлча),
    квантиль берётся из нормального распределения: выборки у нас большие.

    Возвращает словарь {"diff", "lo", "hi", "p"}.
    """
    d = t.mean() - c.mean()
    # Стандартная ошибка разности: дисперсия каждой группы делится на её размер.
    se = (t.var() / len(t) + c.var() / len(c)) ** 0.5
    q = z(1 - alpha / 2)                        # 1.96 при alpha = 0.05
    p = 2 * (1 - NormalDist().cdf(abs(d / se)))  # двустороннее p-значение
    return {"diff": d, "lo": d - q * se, "hi": d + q * se, "p": p}


def srm_pvalue(sizes) -> float:
    """p-значение проверки SRM: χ² согласия с равными долями групп.

    sizes — размеры групп списком, например [3010, 2990].
    Маленькое p (меньше 0.01) значит, что группы разошлись по размеру сильнее,
    чем бывает случайно, и где-то потерялись клиенты.

    Без scipy p-значение χ² выражается через стандартную библиотеку
    только для 2 и 3 групп (1 и 2 степени свободы).
    """
    n = sum(sizes)
    expected = n / len(sizes)                    # сколько ждали в каждой группе
    chi2 = sum((s - expected) ** 2 / expected for s in sizes)
    if len(sizes) == 2:
        return math.erfc(math.sqrt(chi2 / 2))    # 1 степень свободы
    if len(sizes) == 3:
        return math.exp(-chi2 / 2)               # 2 степени свободы
    raise ValueError("для 4 и более групп — scipy.stats.chisquare")


def cuped(y, x):
    """Метрика после поправки CUPED и коэффициент theta.

    y — метрика в периоде эксперимента (например, оборот spend);
    x — ковариата, измеренная СТРОГО до начала эксперимента (например, spend_prev).
    Обе — pandas.Series одной длины.

        y_cuped = y − theta · (x − среднее x),  theta = cov(y, x) / var(x).

    Среднее метрики не меняется, а разброс падает на долю ρ², квадрат корреляции y и x.
    """
    theta = y.cov(x) / x.var()
    return y - theta * (x - x.mean()), theta
